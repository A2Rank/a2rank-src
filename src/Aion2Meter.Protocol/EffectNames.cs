    /// <summary>The name of the effect, or "효과 &lt;id&gt;" when it is not known.</summary>
    public static string Name(uint effectId) => Known(effectId) ?? $"효과 {effectId}";

    /// <summary>The name of the skill that gave the effect (the effect id itself, or without its last digit, as a skill or as a group of ranks); null for the generic effects and unknown ones.</summary>
    public static string? OfSkill(uint effectId) =>
        BuffEffectNames.Of(effectId) is { } buff ? buff
        : SkillNames.TryGetValue(effectId, out var exact) ? exact
        : SkillNames.TryGetValue(effectId / 10, out var skill) ? skill
        : GroupNames.TryGetValue(effectId / 10 / 10000 * 10000, out var group) ? group : null;   // 140500201 -> skill 14050020 -> group 14050000 [송곳 화살]

    /// <summary>The name of the effect; null when it is not known.</summary>
    public static string? Known(uint effectId) => OfGeneric(effectId) ?? OfSkill(effectId);

    /// <summary>The name of an effect named by hand (not a skill's of the table): 기절, 허점 ...; null otherwise.</summary>
    public static string? OfGeneric(uint effectId) => Generic.TryGetValue(effectId, out var generic) ? generic : null;

